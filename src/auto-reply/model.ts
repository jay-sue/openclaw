/**
 * ============================================================================
 * 模型指令提取模块
 * ============================================================================
 *
 * 本模块负责从用户发送的消息文本中解析和提取模型切换指令。
 *
 * 【功能概述】
 * 在聊天场景中，用户可能希望临时切换到特定的 AI 模型来处理当前消息。
 * 本模块提供了从消息中识别这类指令的能力，支持：
 *   - 标准的 `/model <模型名>` 指令格式
 *   - 用户自定义的模型别名快捷方式（如 `/gpt4`、`/claude`）
 *
 * 【使用场景示例】
 * 用户消息: "请帮我 /model gpt-4 分析这段代码"
 * 解析结果: 使用 gpt-4 模型处理 "请帮我分析这段代码"
 *
 * 【模块依赖】
 * - splitTrailingAuthProfile: 用于分离模型名称和认证配置文件后缀
 * - escapeRegExp: 用于安全地将用户配置的别名转换为正则表达式
 */

// 从 model-ref-profile 模块导入函数，用于解析模型引用中的 @profile 后缀
// 例如: "gpt-4@work-account" => { model: "gpt-4", profile: "work-account" }
// 这允许用户指定使用哪个认证配置文件来访问模型
import { splitTrailingAuthProfile } from "../agents/model-ref-profile.js";
// 从工具模块导入正则表达式转义函数
// 用于将用户配置的别名字符串安全地转换为正则表达式模式
// 防止别名中的特殊字符（如 "." 或 "+"）被误解释为正则元字符
import { escapeRegExp } from "../utils.js";

/**
 * ============================================================================
 * extractModelDirective - 核心函数：从消息文本中提取模型指令
 * ============================================================================
 *
 * 【函数职责】
 * 1. 扫描输入的消息文本，查找模型切换指令
 * 2. 提取指令中指定的模型名称
 * 3. 分离模型名称中可能存在的认证配置文件后缀
 * 4. 返回清理后的消息文本（移除指令部分）
 *
 * 【支持的指令格式】
 *
 * 格式一：标准 /model 指令
 * -------------------------
 * 语法: /model [模型名称]
 *
 * 有效示例:
 *   - "/model gpt-4"           → 指定使用 gpt-4 模型
 *   - "/model:gpt-4"           → 冒号紧跟模型名（无空格）
 *   - "/model: gpt-4"          → 冒号后有空格
 *   - "/model openai/gpt-4"    → 带命名空间的模型路径
 *   - "/model gpt-4@work"      → 带认证配置文件后缀
 *   - "请帮我 /model gpt-4 写代码" → 指令在消息中间
 *   - "/model"                 → 仅指令无模型名（hasDirective=true, rawModel=undefined）
 *
 * 无效示例（不会被识别）:
 *   - "/modelfoo"              → model 后紧跟其他字符
 *   - "abc/model gpt-4"        → 斜杠前有其他字符
 *
 * 格式二：模型别名快捷指令
 * -------------------------
 * 语法: /<别名>
 * 前提: 必须在 options.aliases 中预先配置别名列表
 *
 * 假设配置: aliases = ["gpt4", "claude", "gemini"]
 *
 * 有效示例:
 *   - "/gpt4"                  → 等同于 /model gpt4
 *   - "/claude 帮我写代码"      → 使用 claude 模型
 *   - "请 /gemini 分析一下"     → 指令在消息中间
 *
 * 【参数说明】
 *
 * @param body - 原始消息文本
 *   - 类型: string | undefined
 *   - 说明: 用户发送的完整消息内容
 *   - 边界情况:
 *     - undefined 或空字符串: 返回 { cleaned: "", hasDirective: false }
 *     - 纯空白字符串: 返回 { cleaned: "", hasDirective: false }（trim 后为空）
 *
 * @param options - 可选的配置对象
 *   - 类型: { aliases?: string[] } | undefined
 *
 * @param options.aliases - 模型别名列表
 *   - 类型: string[] | undefined
 *   - 说明: 允许用户使用的快捷别名，每个别名可以直接作为 /<别名> 使用
 *   - 示例: ["gpt4", "gpt", "claude", "sonnet", "gemini"]
 *   - 注意事项:
 *     - 别名匹配不区分大小写（/GPT4 和 /gpt4 等效）
 *     - 空字符串和纯空白别名会被自动过滤
 *     - 别名中的特殊正则字符会被自动转义（如 "c++" 不会被误解析）
 *     - 只有在 /model 指令未匹配时才会尝试别名匹配
 *
 * 【返回值说明】
 *
 * @returns 返回一个包含以下属性的对象:
 *
 * @property {string} cleaned - 清理后的消息文本
 *   - 移除了模型指令部分
 *   - 合并了多余的空白字符
 *   - 首尾空白已去除
 *   - 示例: "请帮我 /model gpt-4 写代码" → "请帮我 写代码"
 *
 * @property {string | undefined} rawModel - 提取到的原始模型标识符
 *   - 不包含 @profile 后缀（如果有的话，会被分离到 rawProfile）
 *   - 保留命名空间路径（如 "openai/gpt-4"）
 *   - 如果指令存在但未指定模型名，则为 undefined
 *   - 示例: "/model openai/gpt-4@work" → rawModel = "openai/gpt-4"
 *
 * @property {string | undefined} rawProfile - 提取到的认证配置文件名称
 *   - 从模型名称的 @后缀 中分离出来
 *   - 用于指定使用哪个 API 密钥/认证配置
 *   - 示例: "/model gpt-4@work-account" → rawProfile = "work-account"
 *
 * @property {boolean} hasDirective - 是否检测到模型指令
 *   - true: 找到了 /model 指令或匹配的别名指令
 *   - false: 消息中没有任何模型指令
 *   - 注意: 即使 rawModel 为 undefined，hasDirective 也可能为 true（如单独的 "/model"）
 *
 * 【使用示例】
 *
 * @example
 * // 示例 1: 基本的 /model 指令
 * extractModelDirective("请帮我 /model gpt-4 写一段代码")
 * // 返回:
 * // {
 * //   cleaned: "请帮我 写一段代码",
 * //   rawModel: "gpt-4",
 * //   rawProfile: undefined,
 * //   hasDirective: true
 * // }
 *
 * @example
 * // 示例 2: 使用模型别名
 * extractModelDirective("请帮我 /claude 写一段代码", { aliases: ["claude", "gpt"] })
 * // 返回:
 * // {
 * //   cleaned: "请帮我 写一段代码",
 * //   rawModel: "claude",
 * //   rawProfile: undefined,
 * //   hasDirective: true
 * // }
 *
 * @example
 * // 示例 3: 带有认证配置文件的模型引用
 * extractModelDirective("/model openai/gpt-4@work")
 * // 返回:
 * // {
 * //   cleaned: "",
 * //   rawModel: "openai/gpt-4",
 * //   rawProfile: "work",
 * //   hasDirective: true
 * // }
 *
 * @example
 * // 示例 4: 没有模型指令的普通消息
 * extractModelDirective("今天天气怎么样？")
 * // 返回:
 * // {
 * //   cleaned: "今天天气怎么样？",
 * //   rawModel: undefined,
 * //   rawProfile: undefined,
 * //   hasDirective: false
 * // }
 *
 * @example
 * // 示例 5: 仅有 /model 指令但没有模型名
 * extractModelDirective("/model")
 * // 返回:
 * // {
 * //   cleaned: "",
 * //   rawModel: undefined,
 * //   rawProfile: undefined,
 * //   hasDirective: true
 * // }
 *
 * @example
 * // 示例 6: 使用冒号分隔的格式
 * extractModelDirective("/model:claude-3-sonnet 解释量子计算")
 * // 返回:
 * // {
 * //   cleaned: "解释量子计算",
 * //   rawModel: "claude-3-sonnet",
 * //   rawProfile: undefined,
 * //   hasDirective: true
 * // }
 */
export function extractModelDirective(
  body?: string,
  options?: { aliases?: string[] },
): {
  cleaned: string;
  rawModel?: string;
  rawProfile?: string;
  hasDirective: boolean;
} {
  // ============================================================================
  // 步骤 1: 边界条件检查 - 处理空输入
  // ============================================================================
  // 如果输入为 undefined、null 或空字符串，直接返回空结果
  // 这避免了后续正则匹配时的空指针异常
  if (!body) {
    return { cleaned: "", hasDirective: false };
  }

  // ============================================================================
  // 步骤 2: 尝试匹配标准的 /model 指令
  // ============================================================================
  //
  // 正则表达式详解: /(?:^|\s)\/model(?=$|\s|:)\s*:?\s*([A-Za-z0-9_.:@-]+(?:\/[A-Za-z0-9_.:@-]+)*)?/i
  //
  // 让我们逐部分解析这个正则表达式：
  //
  // ┌─────────────────────────────────────────────────────────────────────────┐
  // │ (?:^|\s)                                                                │
  // │ --------                                                                │
  // │ 非捕获组：匹配字符串开头(^) 或 空白字符(\s)                               │
  // │ 作用：确保 /model 出现在消息开头或前面有空格，防止匹配 "abc/model"        │
  // │ 示例：✓ "/model" ✓ "请 /model" ✗ "abc/model"                            │
  // └─────────────────────────────────────────────────────────────────────────┘
  //
  // ┌─────────────────────────────────────────────────────────────────────────┐
  // │ \/model                                                                 │
  // │ -------                                                                 │
  // │ 字面量匹配 "/model"（斜杠需要转义）                                       │
  // └─────────────────────────────────────────────────────────────────────────┘
  //
  // ┌─────────────────────────────────────────────────────────────────────────┐
  // │ (?=$|\s|:)                                                              │
  // │ ----------                                                              │
  // │ 正向先行断言：/model 后面必须是字符串结尾($)、空白(\s)或冒号(:)           │
  // │ 作用：防止匹配 "/modelfoo" 这样的情况                                    │
  // │ 注意：先行断言不消耗字符，只检查位置                                      │
  // │ 示例：✓ "/model " ✓ "/model:" ✓ "/model\n" ✗ "/modelfoo"                │
  // └─────────────────────────────────────────────────────────────────────────┘
  //
  // ┌─────────────────────────────────────────────────────────────────────────┐
  // │ \s*:?\s*                                                                │
  // │ --------                                                                │
  // │ 可选的分隔符部分：                                                       │
  // │   \s* - 零个或多个空白字符                                               │
  // │   :?  - 零个或一个冒号                                                   │
  // │   \s* - 零个或多个空白字符                                               │
  // │ 作用：灵活处理 "/model gpt" "/model:gpt" "/model: gpt" 等格式            │
  // └─────────────────────────────────────────────────────────────────────────┘
  //
  // ┌─────────────────────────────────────────────────────────────────────────┐
  // │ ([A-Za-z0-9_.:@-]+(?:\/[A-Za-z0-9_.:@-]+)*)?                            │
  // │ ------------------------------------------------                        │
  // │ 捕获组（可选）：匹配模型名称                                              │
  // │                                                                         │
  // │ [A-Za-z0-9_.:@-]+                                                       │
  // │   匹配模型名称的基本部分，允许的字符：                                    │
  // │   - A-Za-z: 大小写字母                                                  │
  // │   - 0-9: 数字                                                           │
  // │   - _: 下划线                                                           │
  // │   - .: 点号（用于版本号如 gpt-4.0）                                      │
  // │   - :: 冒号（某些提供商的模型命名）                                       │
  // │   - @: at符号（用于 @profile 后缀）                                      │
  // │   - -: 连字符（如 gpt-4, claude-3）                                      │
  // │                                                                         │
  // │ (?:\/[A-Za-z0-9_.:@-]+)*                                                │
  // │   可选的路径段：允许斜杠分隔的多段路径                                    │
  // │   示例: "openai/gpt-4", "anthropic/claude-3/sonnet"                     │
  // │                                                                         │
  // │ 整个捕获组末尾的 ? 表示模型名是可选的                                     │
  // │ 这允许单独的 "/model" 指令（不带模型名）也能被识别                        │
  // └─────────────────────────────────────────────────────────────────────────┘
  //
  // ┌─────────────────────────────────────────────────────────────────────────┐
  // │ /i 标志                                                                 │
  // │ -------                                                                 │
  // │ 忽略大小写：/MODEL、/Model、/model 都会被匹配                            │
  // └─────────────────────────────────────────────────────────────────────────┘
  //
  const modelMatch = body.match(
    /(?:^|\s)\/model(?=$|\s|:)\s*:?\s*([A-Za-z0-9_.:@-]+(?:\/[A-Za-z0-9_.:@-]+)*)?/i,
  );

  // ============================================================================
  // 步骤 3: 准备别名列表
  // ============================================================================
  // 从配置中获取别名列表，进行预处理：
  // 1. 如果 options 或 aliases 为 undefined，使用空数组作为默认值
  // 2. 对每个别名进行 trim() 去除首尾空白
  // 3. 使用 filter(Boolean) 过滤掉空字符串（trim 后可能为空）
  //
  // 示例：
  //   输入: ["gpt4", "  claude  ", "", "  ", "gemini"]
  //   输出: ["gpt4", "claude", "gemini"]
  //
  const aliases = (options?.aliases ?? []).map((alias) => alias.trim()).filter(Boolean);

  // ============================================================================
  // 步骤 4: 尝试匹配别名指令（仅在 /model 未匹配时）
  // ============================================================================
  //
  // 别名匹配的触发条件：
  // 1. 标准 /model 指令没有匹配到（modelMatch 为 null）
  // 2. 且配置了至少一个有效的别名（aliases.length > 0）
  //
  // 如果 /model 已经匹配，跳过别名检查（/model 优先级更高）
  // 这确保了 "/model gpt4" 不会被同时匹配为 /model 和 /gpt4
  //
  const aliasMatch =
    modelMatch || aliases.length === 0
      ? null // 跳过别名匹配
      : body.match(
          new RegExp(
            // 动态构建别名匹配的正则表达式
            //
            // 假设 aliases = ["gpt4", "claude", "c++"]
            // 生成的正则: /(?:^|\s)\/(gpt4|claude|c\+\+)(?=$|\s|:)(?:\s*:\s*)?/i
            //
            // 各部分说明：
            //
            // (?:^|\\s)
            //   同上：匹配开头或空白，确保别名指令是独立的
            //
            // \\/(...)
            //   斜杠后跟别名捕获组
            //
            // (${aliases.map(escapeRegExp).join("|")})
            //   将别名数组转换为正则或表达式: (alias1|alias2|alias3)
            //   escapeRegExp 确保特殊字符被正确转义
            //   例如 "c++" 会变成 "c\\+\\+"，防止 + 被解释为"一个或多个"
            //
            // (?=$|\\s|:)
            //   同上：正向先行断言，确保别名后是结尾、空白或冒号
            //
            // (?:\\s*:\\s*)?
            //   可选的冒号分隔符（与 /model 类似，但这里冒号后不期望有值）
            //
            `(?:^|\\s)\\/(${aliases.map(escapeRegExp).join("|")})(?=$|\\s|:)(?:\\s*:\\s*)?`,
            "i", // 忽略大小写
          ),
        );

  // ============================================================================
  // 步骤 5: 确定最终的匹配结果
  // ============================================================================
  //
  // 使用空值合并运算符 (??) 确定优先级：
  // - 如果 modelMatch 存在（不是 null），使用 modelMatch
  // - 否则使用 aliasMatch（可能是匹配结果或 null）
  //
  // 这确保了 /model 指令的优先级高于别名指令
  //
  const match = modelMatch ?? aliasMatch;

  // ============================================================================
  // 步骤 6: 提取原始模型值
  // ============================================================================
  //
  // 根据匹配类型，从不同的捕获组中提取值：
  //
  // 情况 A: modelMatch 存在
  //   - modelMatch[0] 是完整匹配（包括前导空格和 /model）
  //   - modelMatch[1] 是第一个捕获组，即模型名称
  //   - 例如: "/model gpt-4" → modelMatch[1] = "gpt-4"
  //
  // 情况 B: aliasMatch 存在
  //   - aliasMatch[0] 是完整匹配（包括前导空格和斜杠）
  //   - aliasMatch[1] 是别名本身
  //   - 例如: "/gpt4" → aliasMatch[1] = "gpt4"
  //
  // 使用可选链 (?.) 和 trim() 安全地处理可能的 undefined 值
  //
  const raw = modelMatch ? modelMatch?.[1]?.trim() : aliasMatch?.[1]?.trim();

  // ============================================================================
  // 步骤 7: 分离模型名称和认证配置文件
  // ============================================================================
  //
  // 模型引用可能包含 @profile 后缀，用于指定认证配置：
  //   - "gpt-4@personal" → 使用 "personal" 配置文件的 API 密钥
  //   - "openai/gpt-4@work" → 命名空间路径 + 配置文件
  //
  // splitTrailingAuthProfile 函数负责分离：
  //   输入: "gpt-4@work"
  //   输出: { model: "gpt-4", profile: "work" }
  //
  //   输入: "gpt-4"（无后缀）
  //   输出: { model: "gpt-4", profile: undefined }
  //
  let rawModel = raw;
  let rawProfile: string | undefined;

  if (raw) {
    const split = splitTrailingAuthProfile(raw);
    rawModel = split.model; // 纯模型名，不含 @profile
    rawProfile = split.profile; // profile 名称，如果有的话
  }

  // ============================================================================
  // 步骤 8: 清理消息文本
  // ============================================================================
  //
  // 从原始消息中移除模型指令，生成干净的消息文本：
  //
  // 处理流程：
  // 1. 如果找到匹配 (match 不为 null):
  //    a. 用单个空格替换匹配的部分: body.replace(match[0], " ")
  //       - match[0] 包含完整匹配（可能包括前导空格）
  //       - 替换为单个空格保持单词分隔
  //    b. 合并连续空白为单个空格: .replace(/\s+/g, " ")
  //       - 处理替换后可能产生的多个连续空格
  //    c. 去除首尾空白: .trim()
  //
  // 2. 如果没有匹配 (match 为 null):
  //    - 仅去除首尾空白: body.trim()
  //
  // 示例:
  //   输入: "请帮我 /model gpt-4 写代码"
  //   match[0]: " /model gpt-4"
  //   替换后: "请帮我  写代码"
  //   合并空白: "请帮我 写代码"
  //   trim: "请帮我 写代码"
  //
  const cleaned = match ? body.replace(match[0], " ").replace(/\s+/g, " ").trim() : body.trim();

  // ============================================================================
  // 步骤 9: 返回解析结果
  // ============================================================================
  //
  // 返回包含所有解析信息的对象：
  // - cleaned: 可直接发送给 AI 模型的干净文本
  // - rawModel: 用户指定的模型（用于后续的模型查找/切换逻辑）
  // - rawProfile: 认证配置文件名（用于选择正确的 API 密钥）
  // - hasDirective: 指示是否存在指令（用于区分"未指定模型"和"指定了空模型"）
  //
  return {
    cleaned,
    rawModel,
    rawProfile,
    hasDirective: !!match, // 将 match 转换为布尔值：null → false, 其他 → true
  };
}
